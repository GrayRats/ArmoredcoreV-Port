#!/usr/bin/env python3
"""Translate only exact pointer-backed lwz/b thunks missed by ReXGlue discovery."""
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from xex_read_guest_range import extract_image

raw = (ROOT / "games/acv/extracted/default.xex").read_bytes()
sha = hashlib.sha256(raw).hexdigest()
assert sha == "4fac87348f827e84633013375012284cd8c769a3c155a675b2989757e666a12b"
image, base, _, _ = extract_image(raw)
registered = (ROOT / "tmp/acv-rexglue-linux-indexed/generated/conditional-fragments/acv_linux_probe_register.cpp").read_text()
known = {int(x, 16) for x in re.findall(r"SetFunction\(0x([0-9A-F]+),", registered)}
registry = (ROOT / "tmp/xenon-more-mulhd-output/ppc_recomp_shared.h").read_text()
entries = {int(x, 16) for x in re.findall(r"PPC_EXTERN_FUNC\(sub_([0-9A-Fa-f]+)\)", registry)}
items = {}
for address in sorted(entries - known):
    offset = address - base
    if not 0 <= offset <= len(image) - 8:
        continue
    load, branch = struct.unpack_from(">2I", image, offset)
    if load != 0x80630004 or branch >> 26 != 18 or branch & 3:
        continue
    delta = branch & 0x3FFFFFC
    if delta & 0x2000000:
        delta -= 0x4000000
    target = address + 4 + delta
    if target in known:
        items[address] = {"address": hex(address), "target": hex(target),
                          "words": [hex(load), hex(branch)], "nontext_references": []}
text_size = (ROOT / "tmp/scan/text.bin").stat().st_size
for index, (value,) in enumerate(struct.iter_unpack(">I", image[:len(image) // 4 * 4])):
    address = base + index * 4
    if value in items and not 0x822B0000 <= address < 0x822B0000 + text_size:
        items[value]["nontext_references"].append(hex(address))
candidates = [x for x in items.values() if x["nontext_references"]]
# Already translated and registered separately after its observed runtime call.
emitted = [x for x in candidates if int(x["address"], 16) != 0x82350E88]
lines = ["// Generated by tools/native-rexglue/generate_adjusting_thunks.py; do not hand-edit.",
         "// Exact raw PPC translations only. Tail-target semantics remain unverified.",
         '#include "acv_linux_probe_pch.h"',
         "#include <rex/system/function_dispatcher.h>", "#include <stdexcept>"]
for target in sorted({int(x["target"], 16) for x in emitted}):
    lines.append(f"REX_EXTERN(sub_{target:08X});")
for item in emitted:
    address, target = int(item["address"], 16), int(item["target"], 16)
    lines += [f"// @retail 0x{address:08X}; {item['words']}; non-text refs {item['nontext_references']}",
              f"static void AcvThunk{address:08X}(PPCContext& ctx, uint8_t* base) {{",
              "  ctx.r3.u64 = REX_LOAD_U32(ctx.r3.u32 + 4);",
              f"  sub_{target:08X}(ctx, base);", "}"]
lines += ["void AcvRegisterAdjustingThunks(rex::runtime::FunctionDispatcher& dispatcher) {"]
for item in emitted:
    address = int(item["address"], 16)
    lines += [f"  if (dispatcher.GetFunction(0x{address:08X}) != nullptr ||",
              f"      !dispatcher.SetFunction(0x{address:08X}, AcvThunk{address:08X}))",
              f'    throw std::runtime_error("ACV thunk 0x{address:08X} already exists or registration failed");']
lines += ["}"]
out = ROOT / "tmp/acv-native-adjusting-thunks.cpp"
out.write_text("\n".join(lines) + "\n")
report = {"scope": "instruction translation; exact lwz r3,4(r3) plus relative b to registered entry; no invented return values",
          "xex_sha256": sha, "source_sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
          "candidates": candidates, "emitted_count": len(emitted),
          "separately_registered": "0x82350E88", "output": str(out.relative_to(ROOT))}
(ROOT / "logs/acv-native-linux/missing-adjusting-thunks.json").write_text(json.dumps(report, indent=2) + "\n")
print(json.dumps({"pointer_backed_candidates": len(candidates), "emitted": len(emitted), "output": str(out)}))
